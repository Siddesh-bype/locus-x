"""Generate src/scene/campusLayout.ts from OpenStreetMap footprints of the VIT Pune campus.

Run from the repository root: python scripts/build_vit_campus.py   (needs network; Overpass API)
Data (c) OpenStreetMap contributors, ODbL. Heights are estimates: OSM carries no levels here.
Polygons are in campus metres (origin near the campus centre). Each detailed building environment
is pinned to its own outline: CAMPUS_ORIGIN gives the campus-metre point that is that model's (0, 0).
While an environment is open its own outline is hidden, since the detailed floors replace it; for the
main block only the southern annex (below the detailed 60 x 36 m footprint) stays drawn.
"""

import json
import math
import subprocess
from pathlib import Path

LAT0, LON0, K = 18.4637, 73.8683, 111320
WAYS = {
    "boundary": 213874316, "playground": 223964778, "main": 223964770,
    "canteen": 1371963261, "fruit": 1371963468,
    "west": 223964767, "north": 223964769, "east": 223964773,
}
ENV = {"main": "vit_pune_v3", "west": "vit_pune_west_v3", "east": "vit_pune_east_v3", "north": "vit_pune_north_v3"}
MAIN_ORIGIN = (-3.0, -13.0)  # main block's detailed footprint: x -3..57, y -13..23 in campus metres
HEIGHT = {"main": 13, "west": 9, "north": 13, "east": 13, "canteen": 4, "fruit": 3}


def fetch():
    ids = ",".join(str(i) for i in WAYS.values())
    query = f"[out:json][timeout:50];way(id:{ids});out geom;"
    out = subprocess.run(
        ["curl", "-s", "-m", "80", "-A", "locus-x-research/1.0 (local dev)",
         "--data-urlencode", f"data={query}", "https://overpass-api.de/api/interpreter"],
        capture_output=True, check=True,
    ).stdout
    return {e["id"]: e for e in json.loads(out)["elements"]}


def to_campus(way):
    pts = [((p["lon"] - LON0) * K * math.cos(math.radians(LAT0)), (p["lat"] - LAT0) * K) for p in way["geometry"]]
    return [(round(x, 1), round(y, 1)) for x, y in (pts[:-1] if pts[0] == pts[-1] else pts)]


def clip_below(poly, y0):
    """Sutherland-Hodgman: keep the part of poly with y <= y0."""
    out = []
    for i, a in enumerate(poly):
        b = poly[i - 1]
        ina, inb = a[1] <= y0, b[1] <= y0
        if ina != inb:
            t = (y0 - b[1]) / (a[1] - b[1])
            out.append((round(b[0] + t * (a[0] - b[0]), 1), y0))
        if ina:
            out.append(a)
    return out


if __name__ == "__main__":
    ways = fetch()
    polys = {name: to_campus(ways[i]) for name, i in WAYS.items()}
    origin = {ENV["main"]: MAIN_ORIGIN}
    for key in ("west", "east", "north"):
        origin[ENV[key]] = (min(x for x, _ in polys[key]), min(y for _, y in polys[key]))
    fmt = lambda p: json.dumps([list(q) for q in p])
    # (name, polygon, height, hideFor, onlyFor)
    blocks = [
        ("Main block", polys["main"], HEIGHT["main"], ENV["main"], None),
        ("Main block annex", clip_below(polys["main"], MAIN_ORIGIN[1] - 0.2), HEIGHT["main"], None, ENV["main"]),
        ("West block", polys["west"], HEIGHT["west"], ENV["west"], None),
        ("North block", polys["north"], HEIGHT["north"], ENV["north"], None),
        ("East block", polys["east"], HEIGHT["east"], ENV["east"], None),
        ("VIT Canteen", polys["canteen"], HEIGHT["canteen"], None, None),
        ("VIT Fruit Canteen", polys["fruit"], HEIGHT["fruit"], None, None),
    ]
    ground = [("Campus", polys["boundary"], "#e6e9e2"), ("VIT Play Ground", polys["playground"], "#bcd7b0")]
    def entry(n, p, h, hide, only):
        extra = (f", hideFor: {json.dumps(hide)}" if hide else "") + (f", onlyFor: {json.dumps(only)}" if only else "")
        return f"  {{ name: {json.dumps(n)}, polygon: {fmt(p)}, height: {h}{extra} }},\n"

    text = (
        "// Generated by scripts/build_vit_campus.py from OpenStreetMap (c) OpenStreetMap contributors, ODbL.\n"
        "// Footprints are mapped outlines in campus metres; heights are estimates.\n"
        "export type Polygon = [number, number][];\n"
        "export interface CampusBlock { name: string; polygon: Polygon; height: number; hideFor?: string; onlyFor?: string }\n\n"
        "/** Campus-metre point that is each detailed environment's (0, 0). */\n"
        "export const CAMPUS_ORIGIN: Record<string, [number, number]> = {\n"
        + "".join(f"  {k}: {list(v)},\n" for k, v in origin.items())
        + "};\n\n"
        "export const CAMPUS_BLOCKS: CampusBlock[] = [\n"
        + "".join(entry(*b) for b in blocks)
        + "];\n\n"
        "export const CAMPUS_GROUND: { name: string; polygon: Polygon; color: string }[] = [\n"
        + "".join(f"  {{ name: {json.dumps(n)}, polygon: {fmt(p)}, color: {json.dumps(c)} }},\n" for n, p, c in ground)
        + "];\n"
    )
    dest = Path(__file__).resolve().parents[1] / "src/scene/campusLayout.ts"
    dest.write_text(text, encoding="utf-8")
    print(f"Wrote {dest}")
